#!/usr/bin/env python3
"""Generate the benchmark scenarios of the T026 performance loop.

The game binary's script language is the one of docs/AGENT_TESTING.md, T023
(key/pad presses through the real SDL event path, tick waits, a clean quit).
docs/PERFORMANCE.md asks the benchmarks to cover busy gameplay, line clears,
previews, menus, and pause; every scenario below plays through the real SDL
application from the title screen, so the measured work is the work a player
sees, core ticks, rendering, previews and all.

Scenarios are pure functions of the tick budget, so a fixed frame count and
the fixed seed the driver passes make every sample - and every rerun after a
candidate patch - replay the same session. That is what makes before and
after numbers comparable beyond run variance.

  busy TICKS OUT    sustained mixed play: taps, DAS holds, both rotations,
                    hold swaps, soft drop, and a sparse hard drop. The stack
                    stays low, so the whole run is the play scene.
  clears TICKS OUT  spread stacking: rotate, move a cycling number of
                    columns, hard drop. Rows complete and clear; when the
                    round tops out, Play Again starts the next round inside
                    the same run.
  menu TICKS OUT    the title screen: cursor moves, Controls, and back.
  pause TICKS OUT   play, pause, cursor moves under the overlay, resume,
                    repeated.

Usage: t026_gen.py SCENARIO TICKS OUT
"""

import sys


class Script:
    """One scripted session under construction."""

    def __init__(self, title):
        self.lines = ["# %s" % title,
                      "# Generated by tests/harness/t026_gen.py; do not edit."]
        self.ticks = 0

    def say(self, text):
        self.lines.append("# " + text)

    def raw(self, line):
        self.lines.append(line)

    def key(self, name, state="down", wait=2):
        self.lines.append("key %s %s" % (name, state))
        self.wait(wait)

    def tap(self, name, wait=2):
        self.key(name, "down", wait)
        self.key(name, "up", wait)

    def wait(self, ticks):
        self.lines.append("wait %d" % ticks)
        self.ticks += ticks

    def marker(self, text):
        self.lines.append("echo %s" % text)

    def start_game(self):
        self.marker("title to play")
        self.tap("enter", 2)
        self.wait(6)

    def write(self, path):
        with open(path, "w", encoding="ascii") as stream:
            stream.write("\n".join(self.lines) + "\n")
        return self.ticks


# One stretch of busy play: horizontal taps, a DAS hold, both rotations, a
# hold swap, and a soft-drop run. A hard drop closes every fourth stretch
# only, but a long enough session still tops out once (deterministically,
# tick 3983 for seed 31 at 6000 ticks); the game-over tail then draws in
# every sample alike, which the driver's verification claim pins.
def busy_segment(script, index):
    script.marker("busy-%d" % index)
    script.tap("left", 2)
    script.tap("right", 2)
    script.tap("left", 2)
    script.key("left", "down", 2)
    script.wait(26)  # DAS/ARR hold across many ticks
    script.key("left", "up", 2)
    script.tap("x", 2)   # rotate clockwise
    script.tap("z", 2)   # rotate counter-clockwise
    script.tap("c", 2)   # hold
    script.key("down", "down", 2)
    script.wait(18)      # soft drop under gravity
    script.key("down", "up", 2)
    script.tap("z", 2)
    script.tap("x", 2)
    script.tap("right", 2)
    if index % 4 == 3:
        script.key("space", "down", 2)
        script.key("space", "up", 8)


def gen_busy(ticks, path):
    script = Script("T026 busy gameplay benchmark (%d ticks)" % ticks)
    script.start_game()
    index = 0
    while script.ticks < ticks:
        busy_segment(script, index)
        index += 1
    script.say("frames bound ends the run before this quit")
    script.raw("quit")
    script.write(path)
    print("busy: %d ticks scripted (%.1f s at 60 Hz)"
          % (script.ticks, script.ticks / 60.0))
    return 0


# One clear cycle: a short stretch of natural play, then the labeled
# four-line fixture of tests/fixtures (the same one the T023/T024 harness
# sessions use: four rows missing only column 5, a forced vertical I, one
# hard drop, four lines gone). The fixture makes the clear deterministic
# where blind stacking cannot; the cycle's `check` records the cleared-line
# counter, so every benchmark sample carries its own proof that clears
# happened. The busy scenario keeps the empty-board game beside this one.
def gen_clears(ticks, path):
    script = Script("T026 line-clear benchmark (%d ticks; labeled fixture "
                    "four-line-ready from tests/fixtures)" % ticks)
    script.start_game()
    cycles = 0
    while script.ticks < ticks:
        script.marker("clear-cycle-%d" % cycles)
        script.say("natural play between the fixture clears")
        script.tap("left", 2)
        script.tap("right", 2)
        script.tap("x", 2)
        script.tap("z", 2)
        script.key("down", "down", 2)
        script.wait(12)
        script.key("down", "up", 2)
        script.say("labeled fixture: the deterministic four-line clear")
        script.raw("fixture four-line-ready")
        script.wait(2)
        script.tap("x", 2)  # rotate the forced I into the column
        script.key("space", "down", 2)
        script.key("space", "up", 2)
        script.wait(6)
        script.raw("check clear-%d" % cycles)
        script.wait(4)
        cycles += 1
    script.raw("quit")
    script.write(path)
    print("clears: %d ticks scripted, %d fixture cycles (%.1f s at 60 Hz)"
          % (script.ticks, cycles, script.ticks / 60.0))
    return 0


def gen_menu(ticks, path):
    script = Script("T026 title and menu benchmark (%d ticks)" % ticks)
    script.marker("title idle and cursor")
    while script.ticks < ticks:
        script.tap("down", 6)   # Start Game -> Controls -> Options -> Quit
        script.wait(24)
        script.tap("up", 6)
        script.wait(24)
        script.tap("down", 6)   # back toward the submenu items
        script.wait(10)
        script.tap("enter", 4)  # open the highlighted screen
        script.wait(30)
        script.tap("esc", 4)    # back to the title
        script.wait(30)
    script.raw("quit")
    script.write(path)
    print("menu: %d ticks scripted (%.1f s at 60 Hz)"
          % (script.ticks, script.ticks / 60.0))
    return 0


def gen_pause(ticks, path):
    script = Script("T026 pause overlay benchmark (%d ticks)" % ticks)
    script.start_game()
    index = 0
    while script.ticks < ticks:
        script.marker("pause-cycle-%d" % index)
        script.tap("left", 2)
        script.tap("x", 2)
        script.tap("z", 2)
        script.key("down", "down", 2)
        script.wait(14)
        script.key("down", "up", 2)
        script.tap("esc", 4)    # pause
        script.tap("down", 10)  # cursor under the overlay
        script.tap("up", 10)
        script.wait(60)         # the paused scene draws on
        script.tap("enter", 4)  # Resume
        script.wait(20)
        index += 1
    script.raw("quit")
    script.write(path)
    print("pause: %d ticks scripted, %d pause cycles (%.1f s at 60 Hz)"
          % (script.ticks, index, script.ticks / 60.0))
    return 0


GENERATORS = {
    "busy": gen_busy,
    "clears": gen_clears,
    "menu": gen_menu,
    "pause": gen_pause,
}


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in GENERATORS:
        sys.stderr.write(__doc__)
        return 2
    ticks = int(sys.argv[2])
    if ticks <= 0:
        sys.stderr.write("t026_gen: TICKS must be positive\n")
        return 2
    return GENERATORS[sys.argv[1]](ticks, sys.argv[3])


if __name__ == "__main__":
    sys.exit(main())
