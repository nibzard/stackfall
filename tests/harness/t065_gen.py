#!/usr/bin/env python3
"""Generate the T065 profiling scenarios (task T065, docs/PERFORMANCE.md).

The owner's device feedback describes the play this round must measure:
several clockwise and counter-clockwise rotations, left and right movement,
held soft drop, hard drop, repeated rounds, line clears, and pause and
resume, on the keyboard and on the virtual controller. Every scenario below
is a scripted real-SDL session in the language of docs/AGENT_TESTING.md, so
the measured work is the work a player sees.

The device report says the stutter arrives "after initially smooth play",
which is exactly the shape of task T052's mid-round record saves: a round
runs smooth while its score stays under the stored record, then every score
that passes the record writes the file on the gameplay thread. Two save
modes therefore run the same scripts:

  fresh    a fresh save directory, so mid-round record saves fire
  banked   a preloaded unreachable record, so none fire

The scripts keep rounds playing. A `restart` command begins a fresh round
from the same seed on a fixed cadence, chosen so the deterministic round of
the fixed seed never reaches its top-out before the next restart, and the
`verify` phase of the driver measures the game-over share of every scenario
and fails a sample that mostly sat at a game over screen.

Scenarios are pure functions of the tick budget, so a fixed frame count and
the fixed seed make every sample - and every rerun after a fix - replay the
same session. That is what makes before and after numbers comparable beyond
run variance.

  rotate-move TICKS OUT   rotations both ways, taps, and DAS holds
  drops       TICKS OUT   held soft drop and hard drop
  clears      TICKS OUT   labeled four-line fixture cycles with restarts
  pause       TICKS OUT   pause and resume cycles over live play
  pad-mixed   TICKS OUT   the same coverage on the virtual controller
  sustained   TICKS OUT   long mixed play with restarts (the sustained case)

Usage: t065_gen.py SCENARIO TICKS OUT
"""

import sys


class Script:
    """One scripted session under construction."""

    def __init__(self, title):
        self.lines = ["# %s" % title,
                      "# Generated by tests/harness/t065_gen.py; do not edit."]
        self.ticks = 0

    def say(self, text):
        self.lines.append("# " + text)

    def raw(self, line):
        self.lines.append(line)

    def press(self, device, name, wait=2):
        self.raw("%s %s down" % (device, name))
        self.wait(wait)
        self.raw("%s %s up" % (device, name))
        self.wait(wait)

    def key(self, name, wait=2):
        self.press("key", name, wait)

    def pad(self, name, wait=2):
        self.press("pad", name, wait)

    def hold(self, device, name, ticks, wait=2):
        self.raw("%s %s down" % (device, name))
        self.wait(wait)
        self.wait(ticks)
        self.raw("%s %s up" % (device, name))
        self.wait(wait)

    def wait(self, ticks):
        # `wait N` is relative: the script holds N further ticks.
        self.raw("wait %d" % ticks)
        self.ticks += ticks

    def marker(self, text):
        self.raw("echo %s" % text)

    def start_game(self, device):
        self.marker("title to play")
        self.press(device, "enter" if device == "key" else "a", 2)
        self.wait(6)

    def restart_round(self):
        self.marker("restart round")
        self.raw("restart")
        self.wait(4)

    def write(self, path):
        with open(path, "w", encoding="ascii") as stream:
            stream.write("\n".join(self.lines) + "\n")
        return self.ticks


# The restart cadence of each scenario: the number of ticks one round runs
# before the script begins the next one. Calibrated against seed 31 so the
# deterministic round tops out well after the restart lands (the verify
# phase measures the real game-over share and fails a script that lets a
# sample mostly sit at a game over screen).
RESTART_EVERY = {
    "rotate-move": 1500,
    "drops": 700,
    "clears": 1400,
    "pause": 700,
    "pad-mixed": 600,
    "sustained": 1100,
}


class RoundClock:
    """Tracks when the script last began a fresh round.

    A restart cadence needs a moving anchor: the segment length varies, so
    counting from the last restart (not from the session start) keeps one
    round from ever running long enough to park the sample at a game over
    screen.
    """

    def __init__(self, period):
        self.period = period
        self.last = 0

    def due(self, script):
        """Begin a fresh round once the cadence elapsed."""
        if self.period > 0 and script.ticks - self.last >= self.period:
            self.last = script.ticks
            script.restart_round()
            return True
        return False


def gen_rotate_move(ticks, path, device="key"):
    script = Script("T065 rotate and move scenario (%d ticks)" % ticks)
    script.start_game(device)
    index = 0
    clock = RoundClock(RESTART_EVERY["rotate-move"])
    while script.ticks < ticks:
        script.marker("rotate-%d" % index)
        # Several rotations in each direction, mixed, near walls too.
        for name in ("x", "z", "x", "z", "z", "x", "z", "x"):
            script.press("key", name, 2)
        # Left and right taps, then a held auto-shift in each direction.
        for name in ("left", "right", "left", "right", "left"):
            script.press("key", name, 2)
        script.hold("key", "left", 24)
        script.hold("key", "right", 24)
        # Push the piece to a wall and rotate there, so wall kicks run.
        script.hold("key", "left", 12)
        script.press("key", "x", 2)
        script.press("key", "z", 2)
        script.wait(40)
        clock.due(script)
        index += 1
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("rotate-move: %d ticks scripted (%.1f s at 60 Hz)"
          % (total, total / 60.0))
    return 0


def gen_drops(ticks, path, device="key"):
    script = Script("T065 soft and hard drop scenario (%d ticks)" % ticks)
    script.start_game(device)
    index = 0
    clock = RoundClock(RESTART_EVERY["drops"])
    while script.ticks < ticks:
        script.marker("drop-%d" % index)
        # A held soft drop under gravity, the owner's own described move.
        script.hold("key", "down", 26)
        # A little movement and a rotation so the drop is not the only work.
        script.press("key", "left", 2)
        script.press("key", "x", 2)
        script.press("key", "z", 2)
        # A hard drop, then the next piece arrives.
        script.press("key", "space", 6)
        script.wait(10)
        clock.due(script)
        index += 1
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("drops: %d ticks scripted (%.1f s at 60 Hz)" % (total, total / 60.0))
    return 0


def gen_clears(ticks, path, device="key"):
    """Four-line fixture cycles with restarts: repeated rounds and clears."""
    script = Script("T065 line clear scenario (%d ticks)" % ticks)
    script.start_game(device)
    cycles = 0
    clock = RoundClock(RESTART_EVERY["clears"])
    while script.ticks < ticks:
        script.marker("clear-cycle-%d" % cycles)
        # A short stretch of natural play, then the labeled four-line
        # fixture of tests/fixtures (four rows missing only column 5, a
        # forced vertical I, one hard drop, four lines gone). The fixture
        # makes the clear deterministic where blind stacking cannot, and
        # the restart cadence begins a fresh round every few cycles, so the
        # scenario measures repeated rounds and clears, not one long stack.
        script.press("key", "x", 2)
        script.press("key", "left", 2)
        script.hold("key", "down", 10)
        script.raw("fixture four-line-ready")
        script.wait(4)
        script.press("key", "space", 8)
        script.raw("check cleared-%d" % cycles)
        script.wait(6)
        cycles += 1
        clock.due(script)
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("clears: %d ticks scripted (%d fixture cycles, %.1f s at 60 Hz)"
          % (total, cycles, total / 60.0))
    return 0


def gen_pause(ticks, path, device="key"):
    script = Script("T065 pause and resume scenario (%d ticks)" % ticks)
    script.start_game(device)
    index = 0
    clock = RoundClock(RESTART_EVERY["pause"])
    while script.ticks < ticks:
        script.marker("pause-%d" % index)
        # Live play between the pauses: rotations, movement, drops, so the
        # scenario spends most of its time in play and not under the overlay.
        script.press("key", "x", 2)
        script.press("key", "z", 2)
        script.hold("key", "left", 16)
        script.hold("key", "down", 12)
        script.press("key", "space", 6)
        script.wait(20)
        script.press("key", "x", 2)
        # Pause, hold it, move the overlay cursor, then resume.
        script.press("key", "esc", 2)
        script.wait(30)
        script.press("key", "down", 2)
        script.press("key", "up", 2)
        script.wait(10)
        script.press("key", "esc", 2)
        script.wait(10)
        clock.due(script)
        index += 1
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("pause: %d ticks scripted (%d pause cycles)" % (total, index))
    return 0


def gen_pad_mixed(ticks, path):
    """The controller half of the coverage: the same play on the pad."""
    script = Script("T065 virtual controller scenario (%d ticks)" % ticks)
    script.start_game("pad")
    index = 0
    clock = RoundClock(RESTART_EVERY["pad-mixed"])
    while script.ticks < ticks:
        script.marker("pad-%d" % index)
        # A rotates clockwise, B counter-clockwise (specification section 5).
        for name in ("a", "b", "a", "b", "b", "a"):
            script.pad(name, 2)
        # D-pad movement, taps, and held auto-shift.
        for name in ("left", "right", "left"):
            script.pad(name, 2)
        script.hold("pad", "left", 20)
        script.hold("pad", "right", 20)
        # Held soft drop on the D-pad, a hold swap, and hard drops on D-pad
        # up, the default task T067 set (X carries nothing).
        script.hold("pad", "down", 22)
        script.pad("y", 2)
        script.pad("up", 6)
        script.wait(8)
        script.pad("up", 6)
        script.wait(10)
        # Pause and resume through Start, as the device player does.
        if index % 3 == 2:
            script.pad("start", 2)
            script.wait(20)
            script.pad("start", 2)
            script.wait(10)
        clock.due(script)
        index += 1
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("pad-mixed: %d ticks scripted (%.1f s at 60 Hz)"
          % (total, total / 60.0))
    return 0


def gen_sustained(ticks, path):
    """One long mixed session with restarts: the sustained-play case."""
    script = Script("T065 sustained play session (%d ticks)" % ticks)
    script.start_game("key")
    index = 0
    clock = RoundClock(RESTART_EVERY["sustained"])
    while script.ticks < ticks:
        script.marker("sustained-%d" % index)
        for name in ("x", "z", "x", "z"):
            script.press("key", name, 2)
        for name in ("left", "right"):
            script.hold("key", name, 18)
        if index % 2 == 0:
            script.hold("key", "down", 24)
        else:
            script.press("key", "space", 6)
            script.wait(8)
        script.press("key", "c", 2)
        if index % 5 == 4:
            script.press("key", "esc", 2)
            script.wait(25)
            script.press("key", "esc", 2)
            script.wait(8)
        script.wait(30)
        clock.due(script)
        index += 1
    script.raw("quit")
    total = script.write(path)
    print("TICKS %d" % total)
    print("sustained: %d ticks scripted (%.1f s at 60 Hz)"
          % (total, total / 60.0))
    return 0


GENERATORS = {
    "rotate-move": lambda t, p: gen_rotate_move(t, p),
    "drops": lambda t, p: gen_drops(t, p),
    "clears": lambda t, p: gen_clears(t, p),
    "pause": lambda t, p: gen_pause(t, p),
    "pad-mixed": lambda t, p: gen_pad_mixed(t, p),
    "sustained": lambda t, p: gen_sustained(t, p),
}


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in GENERATORS:
        sys.stderr.write(__doc__)
        return 2
    return GENERATORS[sys.argv[1]](int(sys.argv[2]), sys.argv[3])


if __name__ == "__main__":
    sys.exit(main())
